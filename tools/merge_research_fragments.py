#!/usr/bin/env python3
"""Merge research/_fragments/* produced per reconnaissance family into the canonical files:
  research/search_log.csv       (rebuilt from every *_search_log.csv fragment)
  research/source_registry.yaml (merge sources; every entry already in the registry wins on id collision and only gains
                                 discovered_by_queries, so access upgrades such as uploaded or fetched_text are made by
                                 editing the registry entry itself)
Run: uv run python tools/merge_research_fragments.py [--check]   (--check: exit 1 if either file would change)
After a hand edit of the registry, run the merge once: --check passes only when the file equals the tool's YAML dump.
"""
from __future__ import annotations

import argparse
import csv
import io
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
FRAG = ROOT / "research" / "_fragments"
LOG = ROOT / "research" / "search_log.csv"
REG = ROOT / "research" / "source_registry.yaml"
COLS = ["search_date", "family", "query", "tool", "useful", "source_discovered", "source_type", "source_authority",
        "publication_date", "version", "url", "access_date", "access_mode", "relevance", "parameters_extracted",
        "unresolved_questions", "licensing_considerations", "local_archived_filename"]


HEADER = ("# Source registry — single list of every source consulted. Schema: schemas/source.schema.json.\n"
          "# access: uploaded | fetched | fetched_text | snippet_only | blocked | pending_fetch. See research/source_quality_policy.md.\n"
          "# Generated by tools/merge_research_fragments.py from research/_fragments/; entries already in the registry (uploads,\n"
          "# fetched_text sources, access upgrades) are edited by hand and kept on merge.\n")


def render() -> tuple[str, str, str]:
    """The merged search log and source registry as text, plus a summary line; nothing is written."""
    rows: list[dict] = []
    for f in sorted(FRAG.glob("*_search_log.csv")):
        with f.open(newline="") as fh:
            for r in csv.DictReader(fh):
                rows.append({c: (r.get(c) or "") for c in COLS})
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=COLS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    summary = f"search_log.csv: {len(rows)} rows from {len(list(FRAG.glob('*_search_log.csv')))} fragments\n"

    reg = yaml.safe_load(REG.read_text()) or {"sources": []}
    by_id = {s["source_id"]: s for s in reg["sources"]}
    protected = set(by_id)
    added = merged = 0
    for f in sorted(FRAG.glob("*_sources.yaml")):
        doc = yaml.safe_load(f.read_text()) or {}
        for s in doc.get("sources", []):
            sid = s["source_id"]
            if sid in protected:
                # keep the upload entry; add any new query provenance
                q = by_id[sid].setdefault("discovered_by_queries", [])
                for x in s.get("discovered_by_queries", []):
                    if x not in q:
                        q.append(x)
                merged += 1
            elif sid in by_id:
                # same external source found by two families: union lists, keep first text
                base = by_id[sid]
                for key in ("unresolved_questions", "discovered_by_queries", "parameters_extracted"):
                    for x in s.get(key, []) or []:
                        base.setdefault(key, [])
                        if x not in base[key]:
                            base[key].append(x)
                if s.get("notes") and s["notes"] not in (base.get("notes") or ""):
                    base["notes"] = ((base.get("notes") or "") + "\n" + s["notes"]).strip()
                merged += 1
            else:
                by_id[sid] = s
                added += 1
    reg["sources"] = list(by_id.values())
    summary += f"source_registry.yaml: {len(reg['sources'])} sources ({added} added, {merged} merged)"
    return buf.getvalue(), HEADER + yaml.safe_dump(reg, sort_keys=False, allow_unicode=True, width=120), summary


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if either file would change; write nothing")
    check = ap.parse_args(argv).check
    log_text, reg_text, summary = render()
    if check:
        stale = [p.name for p, t in ((LOG, log_text), (REG, reg_text)) if p.read_text() != t]
        if stale:
            print(f"not merged: {', '.join(stale)} would change; run tools/merge_research_fragments.py")
            return 1
        print(f"merged: {summary.replace(chr(10), '; ')}")
        return 0
    with LOG.open("w", newline="") as fh:
        fh.write(log_text)
    REG.write_text(reg_text)
    print(summary)
    return 0


if __name__ == "__main__":
    sys.exit(main())
